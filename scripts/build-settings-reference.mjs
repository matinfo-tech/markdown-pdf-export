#!/usr/bin/env node
/**
 * Generates docs/reference/settings.md from the settings schema and the
 * built-in defaults, so the reference page cannot drift from the code.
 *
 * Usage: node scripts/build-settings-reference.mjs [--check]
 *   --check  exit 1 if the page is out of date instead of writing it
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { buildSettingsSchema } from "../lib/settings-schema.mjs";
import { DEFAULT_SETTINGS } from "../export.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const TARGET = path.join(ROOT, "docs", "reference", "settings.md");

const GROUPS = [
  ["Short presets", "The quickest way to set many things at once.", ["look", "font", "heading_font", "template"]],
  ["Page", "", ["page_format", "orientation", "margin", "scale", "page_ranges", "print_background"]],
  ["Text, fonts and code", "", ["font_family", "heading_font_family", "accent_color", "stylesheet_path", "include_default_styles", "highlight", "highlight_style"]],
  ["Content", "", ["breaks", "emoji", "math", "math_options", "heading_anchors", "toc", "toc_options", "mermaid", "sanitize"]],
  ["Header and footer", "See [Header and footer](/advanced/header-footer).", ["header", "footer", "display_header_footer"]],
  ["Files", "", ["output_directory", "assets_directory", "open_after_export"]],
];
const SKIP = new Set(["$schema"]);

const cell = (s) =>
  String(s ?? "")
    .replace(/\s+/g, " ")
    .replace(/\|/g, "\\|")
    .replace(/\[\[(\w+)\]\]/g, "`[[$1]]`") // VitePress would expand a bare [[toc]]
    .trim();
const code = (v) => `\`${typeof v === "string" ? v : JSON.stringify(v)}\``;

function values(prop) {
  if (prop.$ref) return "object, see below";
  if (prop.enum) {
    if (prop.enum.length > 12) {
      const common = ["github.css", "github-dark.css", "monokai.css"].filter((v) => prop.enum.includes(v));
      const shown = common.length ? common : prop.enum.slice(0, 3);
      return `one of ${prop.enum.length} names, e.g. ${shown.map(code).join(", ")}`;
    }
    return prop.enum.map(code).join(", ");
  }
  if (prop.type === "object" && prop.properties) {
    return `object: ${Object.keys(prop.properties).map(code).join(", ")}`;
  }
  return Array.isArray(prop.type) ? prop.type.join(" or ") : (prop.type ?? "");
}

function defaultOf(key, prop) {
  const d = key in DEFAULT_SETTINGS ? DEFAULT_SETTINGS[key] : prop.default;
  if (d === null || d === undefined || d === "") return "";
  if (typeof d === "object" && !Array.isArray(d)) {
    return Object.entries(d)
      .filter(([, v]) => !(typeof v === "object" && v && !Array.isArray(v) && !Object.keys(v).length))
      .map(([k, v]) => `${k}: ${code(v)}`)
      .join(", ");
  }
  return code(d);
}

export function buildSettingsReference() {
  const schema = buildSettingsSchema();
  const props = schema.properties;
  const placed = new Set(GROUPS.flatMap(([, , keys]) => keys));
  const rest = Object.keys(props).filter((k) => !placed.has(k) && !SKIP.has(k));
  const groups = rest.length ? [...GROUPS, ["Other", "", rest]] : GROUPS;

  const out = [
    "<!-- Generated by scripts/build-settings-reference.mjs from lib/settings-schema.mjs. Do not edit. -->",
    "",
    "# All settings",
    "",
    "Every key a settings file or a project `.markdown-pdf.json` accepts. Most people never need this",
    "page: [Studio](/studio) writes these for you. Where the files live and how they combine:",
    "[Settings file](/advanced/settings-file). Which keys a document's front matter accepts:",
    "[Per-document options](/advanced/per-document).",
    "",
  ];
  for (const [title, intro, keys] of groups) {
    const present = keys.filter((k) => props[k]);
    if (!present.length) continue;
    out.push(`## ${title}`, "");
    if (intro) out.push(intro, "");
    out.push("| Setting | What it does | Values | Default |", "|---|---|---|---|");
    for (const key of present) {
      const p = props[key];
      out.push(`| \`${key}\` | ${cell(p.description)} | ${cell(values(p))} | ${cell(defaultOf(key, p))} |`);
    }
    out.push("");
  }

  const hf = schema.definitions?.header_footer?.properties ?? {};
  if (Object.keys(hf).length) {
    out.push("## Inside `header` and `footer`", "");
    out.push("| Key | What it does | Values |", "|---|---|---|");
    for (const [key, p] of Object.entries(hf)) {
      out.push(`| \`${key}\` | ${cell(p.description)} | ${cell(values(p))} |`);
    }
    out.push("", "The structured form (`left`, `center`, `right` as objects): [Structured header and footer](/reference/header-footer).", "");
  }
  return out.join("\n").replace(/\n+$/, "\n");
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const text = buildSettingsReference();
  const current = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, "utf8").replaceAll("\r\n", "\n") : null;
  if (current === text) {
    process.exitCode = 0;
  } else if (process.argv.includes("--check")) {
    console.error(`✗ ${path.relative(ROOT, TARGET)} is out of date — run: npm run build:reference`);
    process.exitCode = 1;
  } else {
    fs.mkdirSync(path.dirname(TARGET), { recursive: true });
    fs.writeFileSync(TARGET, text);
    console.log(`wrote ${path.relative(ROOT, TARGET)}`);
  }
}
